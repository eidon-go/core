package sql

import (
	"context"
	stdsql "database/sql"
)

// Querier is the narrow contract of the convenience layer (Get, Select,
// Exec), shared by both worlds so that hand-written fakes stay small.
type Querier interface {
	// GetContext scans the only row of the query into dest: ErrNoRows when
	// there is none, ErrTooManyRows when there are more.
	GetContext(ctx context.Context, dest any, query string, args ...any) error
	// SelectContext scans every row of the query into dest, a pointer to a
	// slice.
	SelectContext(ctx context.Context, dest any, query string, args ...any) error
	// ExecContext runs a statement that returns no rows.
	ExecContext(ctx context.Context, query string, args ...any) (stdsql.Result, error)
}

// DBTX is what *sql.DB and *sql.Tx have in common; code generated by sqlc
// for database/sql takes it (New(db DBTX) *Queries).
type DBTX interface {
	ExecContext(ctx context.Context, query string, args ...any) (stdsql.Result, error)
	QueryContext(ctx context.Context, query string, args ...any) (*stdsql.Rows, error)
	QueryRowContext(ctx context.Context, query string, args ...any) *stdsql.Row
	PrepareContext(ctx context.Context, query string) (*stdsql.Stmt, error)
}

// SQLQuerier is a Querier that also passes for a DBTX: the transaction of
// the context or the database, for helpers and sqlc-generated code alike.
type SQLQuerier interface { //nolint:revive // pairs with pgx.PgxQuerier: the world is in the name
	Querier
	DBTX
}

// NewQuerier returns an SQLQuerier over dbtx that scans with scanner
// (DefaultScanner when nil).
func NewQuerier(dbtx DBTX, scanner Scanner) SQLQuerier {
	if scanner == nil {
		scanner = DefaultScanner()
	}

	return querier{DBTX: dbtx, scanner: scanner}
}

type querier struct {
	DBTX

	scanner Scanner
}

func (q querier) GetContext(ctx context.Context, dest any, query string, args ...any) error {
	rows, err := q.QueryContext(ctx, query, args...) //nolint:rowserrcheck // the Scanner checks and closes rows
	if err != nil {
		return err
	}

	return q.scanner.ScanOne(rows, dest) //nolint:wrapcheck // the scanner's error, as is
}

func (q querier) SelectContext(ctx context.Context, dest any, query string, args ...any) error {
	rows, err := q.QueryContext(ctx, query, args...) //nolint:rowserrcheck // the Scanner checks and closes rows
	if err != nil {
		return err
	}

	return q.scanner.ScanAll(rows, dest) //nolint:wrapcheck // the scanner's error, as is
}
